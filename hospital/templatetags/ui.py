@register.simple_tag
def icon(name, size=18):
    body = ICONS.get(name, "")
    return format_html(
        '<svg class="ic" width="{0}" height="{0}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{1}</svg>',
        size, mark_safe(body))


@register.simple_tag
def avatar(obj, size="md"):
    name = getattr(obj, "full_name", "") or "?"
    parts = [p for p in name.split() if p]
    initials = (parts[0][0] + (parts[-1][0] if len(parts) > 1 else "")).upper()
    photo = getattr(obj, "photo", None)
    if photo:
        return format_html('<span class="avatar {}"><img src="{}" alt="{}"></span>', size, photo.url, name)
    return format_html('<span class="avatar {} initials">{}</span>', size, initials)


@register.filter
def money(value):
    try:
        return "Rs. {:,}".format(int(round(float(value or 0))))
    except (TypeError, ValueError):
        return "Rs. 0"


@register.filter
def getitem(d, key):
    return d.get(key)
